          // Mobilný mockup s dynamickým prepínaním obsahu
          function setupMobileMockup() {
              const bannerItems = document.querySelectorAll('.banner-item');
              const mobileScreen = document.getElementById('mobile-screen');
              
              if (bannerItems.length === 0 || !mobileScreen) return;
              
              let hoveredBanner = null;
              
              // Funkcia na nájdenie bannera najbližšie k stredu obrazovky
              function findCenterBanner() {
                  const centerY = window.innerHeight / 2;
                  let closestBanner = null;
                  let closestDistance = Infinity;
                  
                  bannerItems.forEach(item => {
                      const rect = item.getBoundingClientRect();
                      const itemCenterY = rect.top + rect.height / 2;
                      const distance = Math.abs(centerY - itemCenterY);
                      
                      if (distance < closestDistance && rect.top < window.innerHeight && rect.bottom > 0) {
                          closestDistance = distance;
                          closestBanner = item;
                      }
                  });
                  
                  return closestBanner;
              }
              
              // Funkcia na aktiváciu bannera
              function activateBanner(bannerElement) {
                  if (!bannerElement) return;
                  
                  const bannerId = bannerElement.getAttribute('data-banner');
                  
                  // Odstráň active class zo všetkých banner items
                  bannerItems.forEach(item => item.classList.remove('active'));
                  
                  // Pridaj active class k aktuálnemu banner item
                  bannerElement.classList.add('active');
                  
                  // Odstráň active class zo všetkých mobile content
                  const mobileContents = mobileScreen.querySelectorAll('.mobile-content');
                  mobileContents.forEach(content => content.classList.remove('active'));
                  
                  // Pridaj active class k zodpovedajúcemu mobile content
                  const activeMobileContent = mobileScreen.querySelector(`[data-banner="${bannerId}"]`);
                  if (activeMobileContent) {
                      activeMobileContent.classList.add('active');
                  }
              }
              
              // Real-time scroll listener s requestAnimationFrame
              let lastActivatedBanner = null;
              let isScrolling = false;
              let scrollTimeout;
              let rafId = null;
              
              function handleScroll() {
                  // Zruš predchádzajúci animationFrame
                  if (rafId) {
                      cancelAnimationFrame(rafId);
                  }
                  
                  // Použij requestAnimationFrame pre plynulé aktualizácie
                  rafId = requestAnimationFrame(() => {
                      if (!hoveredBanner) {
                          const centerBanner = findCenterBanner();
                          
                          // Aktivuj len ak sa zmenil banner (optimalizácia)
                          if (centerBanner && centerBanner !== lastActivatedBanner) {
                              activateBanner(centerBanner);
                              lastActivatedBanner = centerBanner;
                          }
                      }
                  });
                  
                  // Detekcia konca scrollovania
                  isScrolling = true;
                  clearTimeout(scrollTimeout);
                  scrollTimeout = setTimeout(() => {
                      isScrolling = false;
                  }, 150);
              }
              
              // Hover listeners pre každý banner
              bannerItems.forEach(item => {
                  item.addEventListener('mouseenter', () => {
                      hoveredBanner = item;
                      lastActivatedBanner = item; // Aktualizuj aj lastActivatedBanner
                      activateBanner(item);
                  });
                  
                  item.addEventListener('mouseleave', () => {
                      hoveredBanner = null;
                      // Po opustení myši aktivuj banner v strede
                      setTimeout(() => {
                          if (!hoveredBanner) {
                              const centerBanner = findCenterBanner();
                              if (centerBanner) {
                                  activateBanner(centerBanner);
                                  lastActivatedBanner = centerBanner;
                              }
                          }
                      }, 100); // Skrátené oneskorenie pre rýchlejšiu reakciu
                  });
              });
              
              // Listener pre celú banners-scroll-content sekciu
              const bannersContainer = document.querySelector('.banners-scroll-content');
              if (bannersContainer) {
                  bannersContainer.addEventListener('mouseleave', () => {
                      hoveredBanner = null;
                      // Okamžite aktivuj banner v strede keď opustíme celú sekciu
                      const centerBanner = findCenterBanner();
                      if (centerBanner) {
                          activateBanner(centerBanner);
                          lastActivatedBanner = centerBanner;
                      }
                  });
              }
              
              // Pridaj scroll listener
              window.addEventListener('scroll', handleScroll);
              
              // Globálny mouse listener pre detekciu keď myš opustí banner sekciu
              document.addEventListener('mousemove', (e) => {
                  const bannersContainer = document.querySelector('.banners-scroll-content');
                  if (bannersContainer) {
                      const rect = bannersContainer.getBoundingClientRect();
                      const isOverBanners = e.clientX >= rect.left && 
                                          e.clientX <= rect.right && 
                                          e.clientY >= rect.top && 
                                          e.clientY <= rect.bottom;
                      
                      // Ak myš nie je nad bannermi a máme nastavený hoveredBanner, vymaž ho
                      if (!isOverBanners && hoveredBanner) {
                          hoveredBanner = null;
                          const centerBanner = findCenterBanner();
                          if (centerBanner) {
                              activateBanner(centerBanner);
                              lastActivatedBanner = centerBanner;
                          }
                      }
                  }
              });
              
              // Aktivuj prvý banner na začiatku
              setTimeout(() => {
                  const centerBanner = findCenterBanner();
                  activateBanner(centerBanner || bannerItems[0]);
              }, 100);
          }
          
          // Mobile layout setup
          function setupMobileLayout() {
              const bannerItems = document.querySelectorAll('.banner-item');
              
              function updateMobileLayout() {
                  const isMobile = window.innerWidth <= 768;
                  
                  if (isMobile) {
                      // Pre každý banner nastav CSS custom property pre pseudo-element
                      bannerItems.forEach(item => {
                          const bannerId = item.getAttribute('data-banner');
                          const imagePath = `/img/ilustrations/12_${bannerId}.webp`;
                          item.style.setProperty('--banner-image', `url('${imagePath}')`);
                      });
                  } else {
                      // Desktop - odstráň custom properties
                      bannerItems.forEach(item => {
                          item.style.removeProperty('--banner-image');
                      });
                  }
              }
              
              // Spusti na začiatku
              updateMobileLayout();
              
              // Spusti pri zmene veľkosti okna
              window.addEventListener('resize', updateMobileLayout);
          }
