      <script>
          // Intersection Observer pre detekciu keď element vstúpi do viewportu
          const observerOptions = {
              threshold: 0.5, // Spustí sa keď je 50% elementu viditeľné
              rootMargin: '0px 0px -50px 0px' // Trochu skoršie spustenie
          };
          
          function typeWriter(element, text, speed = 50) {
              element.textContent = '';
              element.classList.add('animate'); // Kurzor sa zobrazí hneď
              let i = 0;
              
              function type() {
                  if (i < text.length) {
                      element.textContent += text.charAt(i);
                      i++;
                      setTimeout(type, speed);
                  }
                  // Kurzor bliká počas celého procesu, nie len na konci
              }
              
              type();
          }
          
          const observer = new IntersectionObserver((entries) => {
              entries.forEach(entry => {
                  if (entry.isIntersecting) {
                      if (entry.target.classList.contains('typing')) {
                          // Pre .typing elementy spusti typeWriter efekt
                          const originalText = entry.target.textContent;
                          typeWriter(entry.target, originalText, 40);
                      } else {
                          // Pre ostatné elementy len pridaj animate class
                          entry.target.classList.add('animate');
                      }
                      // Prestať pozorovať tento element (animácia sa spustí len raz)
                      observer.unobserve(entry.target);
                  }
              });
          }, observerOptions);
          
          // Animácia boxov s postupným zobrazovaním
          function animateBoxes() {
              const boxes = document.querySelectorAll('.boxes .box');
              const boxObserver = new IntersectionObserver((entries) => {
                  entries.forEach((entry, index) => {
                      if (entry.isIntersecting) {
                          // Postupné zobrazovanie s oneskorením
                          setTimeout(() => {
                              entry.target.classList.add('animate-in');
                          }, index * 150); // 150ms oneskorenie medzi boxami
                          
                          boxObserver.unobserve(entry.target);
                      }
                  });
              }, {
                  threshold: 0.2,
                  rootMargin: '0px 0px -50px 0px'
              });
              
              boxes.forEach(box => {
                  boxObserver.observe(box);
              });
          }
          
          // Funkcia na zabránenie popup správaniu videí
          function preventVideoPopups() {
              const videos = document.querySelectorAll('video');
              
              videos.forEach(video => {
                  // Zabráň všetkým interakciám s videom
                  video.addEventListener('click', function(e) {
                      e.preventDefault();
                      e.stopPropagation();
                      return false;
                  });
                  
                  video.addEventListener('touchstart', function(e) {
                      e.preventDefault();
                      e.stopPropagation();
                      return false;
                  });
                  
                  video.addEventListener('touchend', function(e) {
                      e.preventDefault();
                      e.stopPropagation();
                      return false;
                  });
                  
                  video.addEventListener('touchmove', function(e) {
                      e.stopPropagation();
                  });
                  
                  // Zabráň kontextovému menu
                  video.addEventListener('contextmenu', function(e) {
                      e.preventDefault();
                      return false;
                  });
                  
                  // Zabráň drag&drop
                  video.addEventListener('dragstart', function(e) {
                      e.preventDefault();
                      return false;
                  });
                  
                  // Zabráň focus
                  video.addEventListener('focus', function(e) {
                      e.preventDefault();
                      video.blur();
                  });
                  
                  // Nastav atribúty pre zabránenie fullscreen
                  video.setAttribute('disablePictureInPicture', '');
                  video.setAttribute('controlslist', 'nofullscreen nodownload noremoteplayback');
                  video.removeAttribute('controls');
                  
                  // Pre iOS Safari
                  video.setAttribute('webkit-playsinline', '');
                  video.setAttribute('playsinline', '');
              });
          }
          
          // Keď sa stránka načíta, začni pozorovať elementy
          document.addEventListener('DOMContentLoaded', () => {
              // Spusti animáciu boxov
              animateBoxes();
              
              // Zabráň popup správaniu videí
              preventVideoPopups();
              
              // Nastav mobilný mockup s dynamickým obsahom
              setupMobileMockup();
              
              // Nastav mobile layout
              setupMobileLayout();
          });
          
          // Počkaj na načítanie všetkých médií vrátane videí
